"""Master study guide index generator (03_study_guide/README.md) adhering to repo-wiki."""

from __future__ import annotations

from pathlib import Path

from distill.models.curriculum import CoverageReport, CurriculumBackbone, TopicNode


def generate_master_index_markdown(
    backbone: CurriculumBackbone,
    ordered_topics: list[TopicNode],
    coverage: CoverageReport,
    output_path: Path | None = None,
) -> str:
    """Generate the root README.md course study guide dashboard."""
    lines: list[str] = [
        f"# Study Guide: {backbone.course_code} - {backbone.course_title}",
        "",
        "> Authoritative study guide synthesized from course syllabus and lecture decks.",
        "",

        "## Course Dashboard",
        f"- **Coverage Status:** {coverage.coverage_percentage}% covered "
        f"({coverage.covered_topic_count}/{coverage.total_syllabus_topics} syllabus topics)",
        f"- **Uncovered Whiteboard Gaps:** {coverage.uncovered_topic_count} topics "
        "(synthesized via textbook grounding)",
        f"- **Assigned Textbooks:** {', '.join(backbone.textbooks) or 'Standard Course Notes'}",
        "",
        "## Master Curriculum Roadmap",
        "| Ch # | Topic Title | Module | Prerequisites | Exam Weight | Study Guide Link |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    for idx, topic in enumerate(ordered_topics, start=1):
        filename = f"{idx:02d}_{topic.id}.md"
        prereqs = ", ".join([f"`{p}`" for p in topic.prerequisites]) or "None"
        weight = f"{int(topic.exam_weight * 100)}%" if topic.exam_weight else "-"
        lines.append(
            f"| {idx:02d} | {topic.title} | {topic.module_id} | {prereqs} | {weight} | "
            f"[[{filename}\\|Chapter {idx}]] |"
        )

    lines.extend(
        [
            "",
            "## Quick-Reference System Invariants",
            "| Concept | Safety Invariant | Liveness Invariant | Common Trap |",
            "| :--- | :--- | :--- | :--- |",
            (
                "| Logical Clocks | a -> b implies C(a) < C(b) | Monotonic counter | "
                "Concurrent events not ordered |"
            ),
            (
                "| Raft Consensus | Single leader per term | Quorum advances state | "
                "Stale leader split-brain |"
            ),
            (
                "| Two-Phase Commit | All commit or all abort | Coordinator progress | "
                "Blocking on coordinator crash |"
            ),
            "",
            "---",

            "*Generated by Distill: Map-Reduce & Knowledge-Graph Synthesis Pipeline.*",
        ]
    )

    full_md = "\n".join(lines)
    if output_path:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(full_md, encoding="utf-8")

    return full_md
